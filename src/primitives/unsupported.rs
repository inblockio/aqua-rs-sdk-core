/// Explain a known-but-unsupported full-SDK template digest.
pub fn unsupported_template_info(digest: &[u8; 32]) -> Option<(&'static str, &'static str)> {
    UNSUPPORTED_SDK_TEMPLATES
        .iter()
        .find(|(d, _, _)| d == digest)
        .map(|(_, name, requires)| (*name, *requires))
}

